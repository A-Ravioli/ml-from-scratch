"""Cross-chapter API contracts for the `mlfs` library.

Every `mlfs.<module>` is built by learners, topic by topic, inside exercise notebooks
(`@app.function` / `@app.class_definition` cells). Later chapters import earlier work only
through these modules, so their public names and signatures are frozen here. Authors of a
topic MUST define exactly the names listed for that topic under `by_topic`, with exactly the
listed signatures, in both `exercise.py` (stubs) and `solutions/exercise.py`.
`tests/test_contracts.py` checks this against the reference solutions.

Format
------
CONTRACTS[module] = {
    "topics":    [owning topic dirs, in load order]      # == mlfs/registry.toml entry
    "summary":   one line
    "by_topic":  {topic dir: [names that topic's notebook defines]}
    "functions": {name: "(param list)"}                   # no annotations; defaults are literals
    "classes":   {Name: {method: "(self, ...)"}}           # classmethods are listed WITHOUT cls
    "notes":     {name: "shapes / semantics, one line"}
}
Signatures are compared by parameter name, kind, order and default (annotations ignored, so
reference code may annotate freely). Tuple defaults must be tuples, never lists. Properties and
plain attributes are not methods: they are described in `notes`, never listed under `classes`.
Methods inherited unchanged from a contracted base class are not repeated. A notebook may define
extra public helpers (marimo makes `_` names cell-private, so stage functions can't be private),
but they must not collide with other names in the same module, and later chapters must not rely
on anything that isn't listed here. Reference implementations favour clarity over speed (e.g.
linalg.svd/eigh are pure-Python Jacobi methods, seconds at n ~ 300): later chapters use the
NumPy/SciPy equivalent where speed matters (AUTHORING.md §9).

Loading / import rules
----------------------
* A module merges its topics' public definitions in order. While topic k loads, `mlfs.<module>`
  already holds the names of topics 1..k-1, so a topic may import EARLIER topics of its own module
  (`from mlfs.linalg import lu_solve` inside 02·04) but never later ones.
* Every module's owners lie inside one chapter, so cross-chapter imports always point backwards.
* Chapters 00-14 import NumPy (+ stdlib, matplotlib for plotting) only. Chapter 15·07 onward may
  import torch. A torch module may import NumPy-era modules, never the reverse.

See CONVENTIONS for the course-wide data, randomness, estimator, optimizer and torch rules.
"""

