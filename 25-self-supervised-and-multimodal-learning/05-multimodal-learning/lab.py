@app.class_definition
class Vocab:
    """word-level tokenizer: <pad> = 0, <unk> = 1, then the training captions' words."""

    def __init__(self, captions, max_len=12):
        words = sorted({w for c in captions for w in c.split()})
        self.itos = ["<pad>", "<unk>"] + words
        self.stoi = {w: i for i, w in enumerate(self.itos)}
        self.max_len = max_len

    def __call__(self, captions):
        out = torch.zeros(len(captions), self.max_len, dtype=torch.int64)
        for i, c in enumerate(captions):
            ids = [self.stoi.get(w, 1) for w in c.split()][: self.max_len]
            out[i, : len(ids)] = torch.tensor(ids)
        return out


@app.function
def make_captioned_digits(X, y, rng, *, exclude=()):
    """images (n, 3, 32, 32) in [0, 1], captions, and attributes (digit, colour index, position index)."""
    small = X.reshape(len(X), 14, 2, 14, 2).mean(axis=(2, 4)) / 255.0  # 28x28 -> 14x14
    names = list(COLOURS)
    imgs, caps, attrs = [], [], []
    for img, d in zip(small, y):
        while True:
            c = int(rng.integers(len(names)))
            if (names[c], int(d)) not in exclude:
                break
        p = int(rng.integers(4))
        canvas = np.zeros((3, 32, 32), dtype=np.float32)
        r0 = (0 if p < 2 else 16) + int(rng.integers(0, 3))
        c0 = (0 if p % 2 == 0 else 16) + int(rng.integers(0, 3))
        canvas[:, r0:r0 + 14, c0:c0 + 14] = img[None] * np.array(COLOURS[names[c]], dtype=np.float32)[:, None, None]
        t = CAPTION_FORMS[int(rng.integers(len(CAPTION_FORMS)))]
        imgs.append(canvas)
        caps.append(t.format(c=names[c], d=DIGITS[d], p=POSITIONS[p]))
        attrs.append((int(d), c, p))
    return np.stack(imgs), caps, np.array(attrs)


@app.class_definition
class ImageCNN(nn.Module):
    """32x32 RGB -> 64 features: three conv-BN-ReLU-pool blocks and global average pooling."""

    def __init__(self):
        super().__init__()
        def block(c_in, c_out):
            return [nn.Conv2d(c_in, c_out, 3, padding=1), nn.BatchNorm2d(c_out), nn.ReLU(), nn.MaxPool2d(2)]

        self.net = nn.Sequential(*block(3, 32), *block(32, 64), *block(64, 64), nn.AdaptiveAvgPool2d(1), nn.Flatten())

    def forward(self, x):
        return self.net(x)


