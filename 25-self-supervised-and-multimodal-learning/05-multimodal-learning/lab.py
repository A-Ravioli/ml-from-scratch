@app.cell
def _(X_test, models, p1, test_attrs, vocab):
    ui.gate(p1)
    with torch.no_grad():
        img_embs = [m.encode_image(torch.as_tensor(X_test)) for m in models]
    _digits = test_attrs[:, 0]
    _ens = [f"a {c} {{}} in the {p}" for c in COLOURS for p in POSITIONS]
    prompt_sets = {
        "{d}": (["{}"], DIGITS),
        "a {d}": (["a {}"], DIGITS),
        "a photo of a {d}": (["a photo of a {}"], DIGITS),
        "the digit {n}  (numerals)": (["the digit {}"], [str(i) for i in range(10)]),
        "a red {d}": (["a red {}"], DIGITS),
        "a {c} {d} in the {p}, averaged over 28 prompts": (_ens, DIGITS),
    }
    _red = test_attrs[:, 1] == list(COLOURS).index("red")
    _rows, _base = [], None
    for _name, (_tmpl, _names) in prompt_sets.items():
        _acc = np.zeros((len(models), 3))  # seeds x (all, red, other)
        for _k, (_m, _e) in enumerate(zip(models, img_embs)):
            _pred = ex.zero_shot_predict(_e, ex.class_embeddings(_m, _names, _tmpl, vocab)).numpy()
            _ok = _pred == _digits
            _acc[_k] = (_ok.mean(), _ok[_red].mean(), _ok[~_red].mean())
        _unk = sum(vocab.stoi.get(w, 1) == 1 for w in _tmpl[0].format(_names[0]).split())
        _base = _acc if _base is None else _base
        _delta = _acc - _base  # paired by seed: the same model, only the prompt differs
        _rows.append(f"| `{_name}` | " + " | ".join(
            f"{_acc[:, j].mean():.3f} ({_acc[:, j].min():.3f}–{_acc[:, j].max():.3f})" for j in range(3))
            + " | " + " | ".join(f"{_delta[:, j].mean():+.3f} ({_delta[:, j].min():+.3f} to {_delta[:, j].max():+.3f})"
                                 for j in (0, 1)) + f" | {_unk} |")
    mo.md("| prompt | accuracy | on red digits | on other colours | Δ accuracy vs `{d}` | Δ on red digits | "
          "unknown words |\n|---|---|---|---|---|---|---|\n"
          + "\n".join(_rows) + "\n\nmean over 5 training seeds (min–max in brackets). the Δ columns compare each prompt with the bare word on "
          "the SAME model, seed by seed, which removes most of the between-model variation. 3,000 test images (409 red), so "
          "the binomial standard error of one model's overall accuracy is about ±0.007. chance is 0.100. unknown words "
          "map to `<unk>`.")
    return (img_embs,)


