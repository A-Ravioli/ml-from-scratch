"""Generate CONTRACTS.md (the readable version of mlfs/contracts.py).

    python scripts/contracts_doc.py           # rewrite CONTRACTS.md
    python scripts/contracts_doc.py --check   # exit 1 if CONTRACTS.md is out of date
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from mlfs.contracts import CONTRACTS, CONVENTIONS

OUT = Path(__file__).resolve().parent.parent / "CONTRACTS.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# mlfs contracts",
        "",
        "<!-- generated by scripts/contracts_doc.py from mlfs/contracts.py. don't edit by hand. -->",
        "",
        "the frozen public interface of every `mlfs` module. topics that own a module must "
        "define exactly these names, with exactly these parameters (names, order, defaults), in "
        "both `exercise.py` and `solutions/exercise.py`. later chapters may only use what's listed "
        "here. `tests/test_contracts.py` checks the reference solutions. see AUTHORING.md §6.",
        "",
        "## conventions",
        "",
    ]
    for key, text in CONVENTIONS.items():
        lines.append(f"- **{key}**: {text}")
    lines += ["", "## modules", ""]
    lines.append(" · ".join(f"[`{m}`](#mlfs{m})" for m in CONTRACTS))
    for name, spec in CONTRACTS.items():
        notes = spec.get("notes", {})
        lines += ["", f"### mlfs.{name}", "", spec["summary"], ""]
        for topic, names in spec.get("by_topic", {}).items():
            lines.append(f"- `{topic}`: {', '.join(f'`{n}`' for n in names)}")
        lines += ["", "| name | signature | notes |", "|---|---|---|"]
        for fn, sig in spec.get("functions", {}).items():
            lines.append(f"| `{fn}` | `{_cell(sig)}` | {_cell(notes.get(fn, ''))} |")
        for cls, methods in spec.get("classes", {}).items():
            lines.append(f"| **class** `{cls}` | | {_cell(notes.get(cls, ''))} |")
            for m, sig in methods.items():
                lines.append(f"| `{cls}.{m}` | `{_cell(sig)}` | {_cell(notes.get(f'{cls}.{m}', ''))} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("CONTRACTS.md is out of date: run python scripts/contracts_doc.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
